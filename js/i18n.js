const DICTS = { en, hi, mr };

/** The language the user picked (may be 'gu'). */
export function pickedLang() {
  return store.settings().lang || 'en';
}

/** The language the copy is actually shown in (Gujarati falls back to English). */
export function contentLang() {
  const l = pickedLang();
  return DICTS[l] ? l : 'en';
}

export function speechLang() {
  const l = LANGUAGES.find((x) => x.id === contentLang());
  return l ? l.speech : 'en-IN';
}

export function t(key, vars) {
  const dict = DICTS[contentLang()];
  let s = dict[key] ?? en[key];
  if (s === undefined) {
    console.warn(`[i18n] missing key "${key}"`);
    return key;
  }
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  }
  return s;
}
